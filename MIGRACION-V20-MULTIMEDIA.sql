create table if not exists public.product_media (
  id bigint generated by default as identity primary key,
  product_id bigint not null references public.products(id) on delete cascade,
  media_type text not null check (media_type in ('image','video')),
  url text not null,
  storage_path text,
  position integer not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists product_media_product_position_idx
on public.product_media(product_id, position, id);

alter table public.product_media enable row level security;

drop policy if exists "public can read product media" on public.product_media;
create policy "public can read product media"
on public.product_media for select
to anon, authenticated
using (
  exists (
    select 1 from public.products p
    where p.id = product_id
      and (p.visible = true or (select public.is_admin()))
  )
);

drop policy if exists "admin can insert product media" on public.product_media;
create policy "admin can insert product media"
on public.product_media for insert
to authenticated
with check ((select public.is_admin()));

drop policy if exists "admin can update product media" on public.product_media;
create policy "admin can update product media"
on public.product_media for update
to authenticated
using ((select public.is_admin()))
with check ((select public.is_admin()));

drop policy if exists "admin can delete product media" on public.product_media;
create policy "admin can delete product media"
on public.product_media for delete
to authenticated
using ((select public.is_admin()));

grant select on public.product_media to anon, authenticated;
grant insert, update, delete on public.product_media to authenticated;
grant usage, select on sequence public.product_media_id_seq to authenticated;

-- Ampliamos el bucket existente para aceptar también videos.
update storage.buckets
set public = true,
    file_size_limit = 52428800,
    allowed_mime_types = array[
      'image/jpeg','image/png','image/webp',
      'video/mp4','video/webm','video/quicktime'
    ]
where id = 'product-images';

